class Builder:
    """Preparation-only IO. Reader never derives expected source hashes here."""
    def sha(self, path):
        name = os.fspath(path)
        prefix = name.rsplit('/', 1)[0] + '/' if name != os.path.normpath(name) else None
        endpoint, _ = path_binding(name, links(), prefix)
        digest = hashlib.sha256()
        with open(endpoint, 'rb') as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b''):
                digest.update(block)
        require(path_binding(name, links(), prefix)[0] == endpoint, 'Preparation path changed')
        return digest.hexdigest()

    def pin(self, pins, path, expected=None):
        name = os.fspath(path)
        actual = self.sha(name)
        require(expected in (None, actual) and pins.get(name, actual) == actual, 'Preparation pin drift')
        pins[name] = actual
        return Path(name)

    def load_sealed(self, path, expected):
        require(self.sha(path) == expected, 'Preparation seal differs')
        raw = Path(path).read_bytes()
        require(hashlib.sha256(raw).hexdigest() == expected, 'Preparation bytes changed')
        return json.loads(raw)


def preparation_context():
    phase = Builder()
    frozen = wiring.clone(wiring.population.frozen, sha=phase.sha, pin=phase.pin,
                          load_sealed=phase.load_sealed)
    owner = SimpleNamespace(Path=Path, json=json, copy=copy, frozen=frozen, phase=phase)
    return wiring.source_context732(owner), phase


def generated_catalog(output):
    require(output.parent == OUT and output.resolve() == output and not output.is_symlink(),
            'Generated evidence requires exact direct output')
    names = {'applied.el', 'after-root.el', 'reloaded.el', 'initial-empty.el',
             'reset-empty.el', 'final-empty.el', 'session-final-empty.el', 'selected_tests.txt',
             'summary_raw.csv', 'summary_applied.csv', 'summary_reset.csv', 'rooted-metrics.csv',
             'gui-contract.tsv', 'live-identity.json', 'execution.json', 'integrity-before.json',
             'integrity-after.json', 'DVEfiles/dve_gui.log', 'launcher.log'}
    for group in wiring.population.frozen.GROUPS:
        names.update(group + '/states_' + stage + '.tsv' for stage in wiring.eight.STAGES)
    names.update('lzc/states_' + stage + '.tsv' for stage in wiring.eight.STAGES)
    names.update('snapshot/states_' + stage + '.csv' for stage in wiring.eight.STAGES)
    return tuple(output / name for name in sorted(names))


def capture_generated(output, baseline_pins):
    """Exact output catalog, non-symlink parents, hashes before semantic review."""
    pins = {}
    for path in generated_catalog(output):
        require(str(path) not in baseline_pins, 'Generated/source authority overlap')
        require(path.is_file() and not path.is_symlink() and path.resolve() == path,
                'Missing/aliased generated evidence: ' + str(path))
        pins[str(path)] = Builder().sha(path)
    return pins


def read_six(output, seal):
    context, builder = preparation_context()
    config = builder.load_sealed(output / 'config.json', seal)
    require(config['population'] == 732 and config['admission_manifest_sha256'] == wiring.root732.SEAL,
            'Exact historical732 only')
    context.check_config(config, output)
    return context, config


def family():
    builder = Builder()
    frozen = wiring.clone(wiring.population.frozen, sha=builder.sha, pin=builder.pin,
                          load_sealed=builder.load_sealed)
    six = SimpleNamespace(**dict(vars(wiring.population), read_config=read_six))
    eight = wiring.clone(wiring.eight, six=six, frozen=frozen)
    shared = wiring.clone(wiring.fixed.shared, frozen=frozen)
    return wiring.clone(wiring.fixed, eight=eight, six=six, frozen=frozen, shared=shared)


def save(path, value):
    with path.open('x') as stream:
        json.dump(value, stream, sort_keys=True, indent=2)
        stream.write('\n')


def runtime_tool(owner):
    # /proc is live execution evidence, never a sealed source-cache role.
    # Preserve original launch/executable attestation functions and their real
    # procfs IO. Only stable source/tool revalidation consumes epoch bytes.
    return SimpleNamespace(**dict(vars(owner.tool), **{name: getattr(wiring.lifecycle.tool, name)
        for name in ('process_info', 'verify_launch_child', 'verify_live_executable')}))


def prepare(output, six_output=None, six_seal=None):
    require(output.parent == OUT and output.resolve() == output and not output.exists(), 'Fresh direct output required')
    siblings = {name: output.with_name(output.name + '-' + name) for name in ('six', 'seven', 'eight')}
    require(not any(p.exists() for p in siblings.values()), 'Preexisting base preparation forbidden')
    backend = family()
    context, builder = preparation_context()
    if six_output is None:
        require(six_seal is None, 'Unexpected six seal')
        wiring.population.prepare(siblings['six'], context)
        six_output = siblings['six']
        six_seal = builder.sha(six_output / 'config.json')
    else:
        require(six_seal, 'Explicit existing six seal required')
        read_six(six_output, six_seal)
    planner = wiring.clone(seven_plan, frozen=backend.frozen, sha=builder.sha)
    planner.prepare(six_output, six_seal, wiring.eight.SOURCE_PROOF, siblings['seven'])
    seven_seal = builder.sha(siblings['seven'] / 'application-plan.json')
    backend.eight.prepare(siblings['eight'], six_output, six_seal,
                          siblings['seven'], seven_seal, True)
    eight_seal = builder.sha(siblings['eight'] / 'runtime-plan.json')
    backend.prepare(output, siblings['eight'], eight_seal, 732)
    fixed_seal = builder.sha(output / backend.PLAN)
    _, config = backend.read_config(output, fixed_seal)
    pins = dict(config['pins'])
    builder.pin(pins, output / backend.PLAN, fixed_seal)
    for path in dependencies():
        builder.pin(pins, path)
    # Explicit roles come from pinned file suffixes, not unpinned file discovery.
    byte_paths = [p for p in pins if Path(p).suffix in ('.json', '.csv', '.tsv', '.txt', '.el', '.tcl', '.py')]
    json_paths = [p for p in byte_paths if Path(p).suffix == '.json']
    plan = dict(schema='EIGHT_EPOCH_HISTORICAL732_REPORT_V1', output=str(output), population=732,
                admission=str(wiring.root732.ADMISSION), admission_seal=wiring.root732.SEAL,
                fixed_seal=fixed_seal, pins=pins, byte_paths=byte_paths, json_paths=json_paths,
                generated_paths=[str(p) for p in generated_catalog(output)],
                targets=5892, protected=17774, audited=23666,
                launch_approved=False, application_approval=False, new_RTL_signoff=False)
    save(output / PLAN, plan)
    return builder.sha(output / PLAN)


def prepare_reader_entry(output, fixed_seal):
    """Fresh entry only for already prepared fixed bytes; never rewrite bases."""
    require(output.parent == OUT and output.resolve() == output and not (output / PLAN).exists(),
            'Fresh reader entry in direct prepared directory required')
    builder = Builder()
    fixed_path = output / wiring.fixed.PLAN
    fixed_plan = builder.load_sealed(fixed_path, fixed_seal)
    require(fixed_plan['schema'] == 'EIGHT_CSV_DEPENDENCY_ONLY_SUCCESSOR_V1'
            and fixed_plan['output'] == str(output) and type(fixed_plan['population']) is int
            and fixed_plan['population'] == 732 and fixed_plan['admission_sha256'] == wiring.root732.SEAL
            and all(fixed_plan[k] is False for k in ('application_approval', 'launch_approved',
                    'automatic_retry', 'official_denominator_verified', 'new_RTL_signoff')),
            'Exact prepared historical732 fixed contract required')
    pins = dict(fixed_plan['pins'])
    builder.pin(pins, fixed_path, fixed_seal)
    for path in dependencies():
        builder.pin(pins, path)
    byte_paths = [p for p in pins if Path(p).suffix in ('.json', '.el', '.tcl', '.py', '.txt')
                  or Path(p).suffix in ('.csv', '.tsv') and
                  (Path(p).name.startswith(('states_', 'summary', 'rooted-'))
                   or Path(p).name == 'gui-contract.tsv')]
    plan = dict(schema='EIGHT_EPOCH_HISTORICAL732_REPORT_V1', output=str(output), population=732,
                admission=str(wiring.root732.ADMISSION), admission_seal=wiring.root732.SEAL,
                fixed_seal=fixed_seal, pins=pins, byte_paths=byte_paths,
                json_paths=[p for p in byte_paths if p.endswith('.json')],
                generated_paths=[str(p) for p in generated_catalog(output)],
                targets=5892, protected=17774, audited=23666,
                launch_approved=False, application_approval=False, new_RTL_signoff=False)
    save(output / PLAN, plan)
    return builder.sha(output / PLAN)


def check(output, seal, generated=False):
    builder = Builder()
    plan = builder.load_sealed(output / PLAN, seal)
    require(plan['schema'] == 'EIGHT_EPOCH_HISTORICAL732_REPORT_V1' and
            plan['output'] == str(output) and plan['population'] == 732 and
            plan['admission'] == str(wiring.root732.ADMISSION) and plan['admission_seal'] == wiring.root732.SEAL
            and (plan['targets'], plan['protected'], plan['audited']) == (5892, 17774, 23666)
            and all(plan[k] is False for k in ('launch_approved', 'application_approval', 'new_RTL_signoff'))
            and plan['generated_paths'] == [str(p) for p in generated_catalog(output)], 'Report contract differs')
    pins = dict(plan['pins'])
    require(all(pins.get(str(path)) == builder.sha(path)
                for path in dependencies()),
            'Mandatory actual reader/entry/test dependency missing or changed')
    require(not set(plan['generated_paths']) & set(pins), 'Generated/source authority overlap')
    pins[str(output / PLAN)] = seal
    bytes_paths, json_paths = list(plan['byte_paths']) + [str(output / PLAN)], list(plan['json_paths']) + [str(output / PLAN)]
    produced = capture_generated(output, pins) if generated else {}
    pins.update(produced)
    bytes_paths.extend(produced)
    json_paths.extend(p for p in produced if p.endswith('.json'))
    owner = wiring.Wiring(pins, bytes_paths, json_paths)
    captured_output = owner.Path(output)
    _, config = owner.fixed.read_config(captured_output, plan['fixed_seal'])
    owner.check_inputs(config)
    if generated:
        result = owner.fixed.verify(captured_output, plan['fixed_seal'])
        require(set(result['files']) <= set(pins), 'Verifier read unlisted evidence')
        require(capture_generated(output, plan['pins']) == produced,
                'Generated bytes changed during semantic verification')
        # Generated hashes remain observations; do not put them in source integrity records.
        result['generated_evidence_pins'] = produced
    else:
        result = dict(status='PREPARED_HISTORICAL732_EPOCH_CHECK_PASS_NO_DVE', population=732)
    owner.phase.check_pins(pins)
    result['epoch'] = owner.phase.finish()
    return result


def run_reviewed(output, seal):
    """Foreground parent-reviewed entry; never called by prepare/check."""
    builder = Builder()
    plan = builder.load_sealed(output / PLAN, seal)
    check(output, seal)
    pins = dict(plan['pins'], **{str(output / PLAN): seal})
    owner = wiring.Wiring(pins, [*plan['byte_paths'], str(output / PLAN)],
                          [*plan['json_paths'], str(output / PLAN)])
    _, config = owner.fixed.read_config(owner.Path(output), plan['fixed_seal'])
    owner.phase.check_pins(pins)
    owner.phase.finish()
    require(json.loads((output / 'status.json').read_bytes())['status'] == 'PREPARED_NO_DVE',
            'Only fresh prepared report may run')
    # Exclusive claim survives failure and prevents automatic retries.
    save(output / 'epoch-launch-claim.json', dict(report_plan_sha256=seal, population=732,
          pid=os.getpid(), automatic_retry=False, application_approval=False))
    boundaries = []

    def checkpoint(actual):
        require(actual == config and len(boundaries) < 2, 'Unexpected integrity checkpoint')
        stage = 'live' if not boundaries else 'post'
        owner.check_inputs(config, boundary=stage)
        owner.phase.check_pins(pins)
        owner.phase.finish()
        boundaries.append(stage)

    bridge = wiring.clone(wiring.lifecycle, tool=runtime_tool(owner), check_inputs=checkpoint)
    original_import = builtins.__import__

    def local_import(name, *args, **kwargs):
        return bridge if name == 'capture_operand_1144' else original_import(name, *args, **kwargs)

    def read_adapter(path, expected):
        require(path == output and expected == plan['fixed_seal'], 'Run config identity differs')
        return config

    def verify_adapter(path, actual):
        require(path == output and actual == config and boundaries == ['live', 'post'],
                'Both fresh integrity checkpoints required before generated verification')
        result = check(output, seal, True)
        result['report_plan_sha256'] = seal
        result['reader_epoch_source_boundaries'] = list(boundaries)
        return result

    # Original run body performs actual executable attestation, timeout, cleanup,
    # returncode and result writing. Only reader/checkpoint/verifier IO is private.
    wiring.population.private(wiring.population.frozen.run,
        read_config=read_adapter, verify_artifacts=verify_adapter,
        __builtins__=dict(vars(builtins), __import__=local_import))(output, plan['fixed_seal'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('prepare', 'prepare-reader-entry', 'check', 'verify', 'run-reviewed'))
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--seal')
    parser.add_argument('--six-output', type=Path)
    parser.add_argument('--six-seal')
    parser.add_argument('--fixed-seal')
    args = parser.parse_args()
    output = args.output.absolute()
    if args.mode == 'prepare':
        require(args.seal is None and args.fixed_seal is None, 'No seal on fresh preparation')
        require(bool(args.six_output) == bool(args.six_seal), 'Both existing six bindings required')
        result = dict(status='PREPARED_NO_DVE', seal=prepare(output,
            args.six_output.absolute() if args.six_output else None, args.six_seal))
    elif args.mode == 'prepare-reader-entry':
        require(args.fixed_seal and not args.seal and not args.six_output and not args.six_seal,
                'Exact fixed source seal only')
        result = dict(status='READER_ENTRY_PREPARED_CHECK_REQUIRED_NO_DVE',
                      seal=prepare_reader_entry(output, args.fixed_seal))
    else:
        require(not args.six_output and not args.six_seal, 'No preparation inputs on sealed reader')
        require(args.fixed_seal is None, 'No source reprepare on sealed reader')
        require(args.seal, 'Explicit report seal required')
        if args.mode == 'run-reviewed':
            run_reviewed(output, args.seal)
            result = dict(status='RUN_TERMINAL', population=732)
        else:
            result = check(output, args.seal, args.mode == 'verify')
    print(json.dumps(result))


if __name__ == '__main__':
    main()
