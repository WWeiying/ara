#!/usr/bin/env python3
"""Prepare-only FP16/policy/reduction/FOF supplement; never invoke VCS."""
import argparse
import json
from pathlib import Path

from generate_rvv_memory_gaps import ROOT, DEST


def narrow_half(bits, rm):
    """Integer IEEE binary32->binary16; RISC-V flags, tininess after rounding.

    rm=0..4 denotes RNE/RTZ/RDN/RUP/RMM; 6 is round-to-odd (jam).
    No host floating-point operations or DUT implementation are used.
    """
    if not 0 <= bits < 1 << 32 or rm not in (0, 1, 2, 3, 4, 6):
        raise ValueError("invalid conversion input")
    sign, exponent, fraction = bits >> 31, (bits >> 23) & 255, bits & 0x7fffff
    if exponent == 255:
        if fraction:
            return 0x7e00, 0 if fraction & 0x400000 else 16
        return (sign << 15) | 0x7c00, 0
    n = (1 << 23) | fraction if exponent else fraction
    scale = exponent - 150 if exponent else -149
    if not n:
        return sign << 15, 0
    e = n.bit_length() - 1 + scale
    quantum = max(e - 10, -24)
    shift = quantum - scale
    q, remainder = divmod(n, 1 << shift) if shift > 0 else (n << -shift, 0)
    if remainder:
        halfway = 1 << (shift - 1)
        increment = (rm == 0 and (remainder > halfway or remainder == halfway and q & 1)
                     or rm == 4 and remainder >= halfway
                     or rm == 2 and sign or rm == 3 and not sign)
        q = q | 1 if rm == 6 else q + bool(increment)
    rounded_e = q.bit_length() - 1 + quantum if q else -1000
    if rounded_e > 15:
        infinity = rm in (0, 4) or rm == 2 and sign or rm == 3 and not sign
        return (sign << 15) | (0x7c00 if infinity else 0x7bff), 5
    if rounded_e < -14:
        result = q << (quantum + 24)
    else:
        distance = quantum - (rounded_e - 10)
        significand = q << distance if distance >= 0 else q >> -distance
        result = ((rounded_e + 15) << 10) | (significand - 1024)
    flags = (1 | (2 if result < 0x400 else 0)) if remainder else 0
    return (sign << 15) | result, flags


def widen_half(bits):
    sign, exponent, fraction = bits >> 15, (bits >> 10) & 31, bits & 1023
    if exponent == 31:
        return 0x7fc00000 if fraction else (sign << 31) | 0x7f800000
    if exponent:
        return (sign << 31) | ((exponent + 112) << 23) | (fraction << 13)
    if not fraction:
        return sign << 31
    e = fraction.bit_length() - 1 - 24
    return (sign << 31) | ((e + 127) << 23) | ((fraction << (23 - (e + 24))) & 0x7fffff)


def fp_inputs():
    # Exact, midpoint, near-midpoint, subnormal, overflow, zero and NaN inputs.
    values = [0, 0x80000000, 0x3f800000, 0xbf800000,
              0x3f801000, 0x3f803000, 0xbf801000, 0xbf803000,
              0x3f800fff, 0x3f801001, 0xbf800fff, 0xbf801001,
              0x33000000, 0xb3000000, 0x33000001, 0xb3000001,
              0x00000001, 0x80000001, 0x387fffff, 0xb87fffff,
              0x477fe000, 0x477ff000, 0xc77fe000, 0xc77ff000,
              0x47800000, 0xc7800000, 0x7f800000, 0xff800000,
              0x7fc00001, 0x7f800001, 0xff800001, 0xffc00001]
    values += [widen_half(x) for x in (1, 0x3ff, 0x400, 0x3555, 0x8001, 0x83ff)]
    return [values[i % len(values)] for i in range(65)]


def cases():
    result = []
    for rm, rounding in ((0, "rne"), (1, "rtz"), (2, "rdn"), (3, "rup"), (4, "rmm"), (6, "rod")):
        for lmul in (4,):
            result.append((f"vrvv_gap29_fp16_{rounding}_m{lmul}", 0, 16, lmul, rm, 0))
    return result


def render(case):
    name, kind, eew, lmul, rm, maximum = case
    lines = ["// SPDX-License-Identifier: SHL-0.51",
             "// Generated by verification/tests/generate_rvv_gap29.py.",
             f'#define N_NAME "{name}"', f"#define N_KIND {kind}",
             f"#define N_EEW {eew}", f"#define N_LMUL m{lmul}",
             f"#define N_RM {rm if rm != 6 else 0}", f"#define N_MAX {maximum}",
             f'#define N_REDUCE "vfred{"max" if maximum else "min"}.vs v3, v8, v1, v0.t\\n"',
             f'#define N_NARROW "vfncvt.{"rod." if rm == 6 else ""}f.f.w v16, v8, v0.t\\n"']
    if kind == 0:
        values = fp_inputs()
        converted = [narrow_half(x, rm) for x in values]
        for name_, data in (("INPUT", values), ("HALF", [x[0] for x in converted]),
                            ("FLAGS", [x[1] for x in converted]),
                            ("WIDE", [widen_half(x[0]) for x in converted])):
            lines.append(f'#define N_{name_} {{' + ", ".join(hex(x) for x in data) + "}")
    lines += ['#include "vrvv_gap29_body.h"', ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEST)
    parser.add_argument("--selection", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    selection = {"tests": ["rvv:" + c[0] for c in cases()]}
    if args.selection:
        if args.check:
            if json.loads(args.selection.read_text()) != selection:
                raise SystemExit("selection mismatch")
        else:
            args.selection.write_text(json.dumps(selection, indent=2) + "\n")
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
    for case in cases():
        target, source = args.output_dir / (case[0] + ".c"), render(case)
        if args.check:
            if target.read_text() != source:
                raise SystemExit(f"generated source differs: {target}")
        else:
            target.write_text(source)


if __name__ == "__main__":
    main()
