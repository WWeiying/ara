#!/usr/bin/env python3
"""Generate 40 bounded rv64uv memory cases; never modify Makefrag."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "apps/riscv-tests/isa/rv64uv"


def matrix_cases():
    for nf in (5, 6, 7):
        for eew in (8, 16, 32, 64):
            for mode in ("unit", "strided", "indexed"):
                yield f"vmemory_gap_nf{nf}_e{eew}_{mode}", nf, eew, mode, eew
    for eew in (8, 16, 32, 64):
        yield f"vmemory_gap_vloxei64_e{eew}", 1, eew, "indexed", 64


def cases():
    preflight = ("vmemory_gap_nf7_e64_strided", "vmemory_gap_vloxei64_e8")
    return sorted(matrix_cases(), key=lambda case:
                  preflight.index(case[0]) if case[0] in preflight else 2)


def instructions(nf, eew, mode, index_eew):
    if mode == "unit":
        load, store = f"vlseg{nf}e{eew}.v", f"vsseg{nf}e{eew}.v"
        operand = "v8, (%[base])"
        return load, store, load, store, operand
    if mode == "strided":
        load, store = f"vlsseg{nf}e{eew}.v", f"vssseg{nf}e{eew}.v"
        operand = "v8, (%[base]), %[stride]"
        return load, store, load, store, operand
    segment = f"seg{nf}" if nf > 1 else ""
    return (f"vlux{segment}ei{index_eew}.v",
            f"vsux{segment}ei{index_eew}.v",
            f"vlox{segment}ei{index_eew}.v",
            f"vsox{segment}ei{index_eew}.v", "v8, (%[base]), v24")


def render(case):
    name, nf, eew, mode, index_eew = case
    lu, su, lo, so, operand = instructions(nf, eew, mode, index_eew)
    lines = ["// SPDX-License-Identifier: SHL-0.51",
             "// Generated by verification/tests/generate_rvv_memory_gaps.py.",
             f'#define GAP_NAME "{name}"', f"#define GAP_NF {nf}",
             f"#define GAP_EEW {eew}", f"#define GAP_INDEX_EEW {index_eew}",
             f"#define GAP_INDEXED {int(mode == 'indexed')}",
             f"#define GAP_ROW {nf if mode == 'unit' else nf + 2}"]
    for define, insn in (("LU", lu), ("SU", su), ("LO", lo), ("SO", so)):
        lines.append(f'#define GAP_{define} "{insn} {operand}"')
    for define, insn in (("SEED", "vle"), ("DUMP", "vse")):
        # Each field occupies one m1 register, with a fixed eight-element slot.
        text = "".join(f"{insn}{eew}.v v{8 + f}, (t0)\\n"
                       f"addi t0, t0, {8 * eew // 8}\\n" for f in range(nf))
        lines.append(f'#define GAP_{define} "{text}"')
    lines.append('#include "vmemory_gap_body.h"')
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEST)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--selection", type=Path,
                        help="write parent-runner selection JSON")
    args = parser.parse_args()
    if args.selection:
        args.selection.write_text(json.dumps(
            {"tests": ["rvv:" + case[0] for case in cases()]}, indent=2) + "\n")
    if args.list:
        print("\n".join(case[0] for case in cases()))
        return
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
    for case in cases():
        path = args.output_dir / (case[0] + ".c")
        expected = render(case)
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"generated source differs: {path}")
        else:
            path.write_text(expected)


if __name__ == "__main__":
    main()
