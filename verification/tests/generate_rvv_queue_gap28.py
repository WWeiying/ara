#!/usr/bin/env python3
"""Generate 36 bounded queue/dependency tests without changing the catalog."""
import argparse
import json
from pathlib import Path

from generate_rvv_memory_gaps import ROOT, DEST


def cases():
    result = []
    for eew in (8, 16, 32):
        for lmul in (1, 4):
            for signed in (0, 1):
                name = f"vqueue_gap28_widen_{'s' if signed else 'u'}_e{eew}_m{lmul}"
                result.append((name, 0, eew, lmul, signed))
    for family, kind in (("slide", 1), ("store", 2)):
        for eew in (8, 16, 32, 64):
            for lmul in (1, 2, 4):
                result.append((f"vqueue_gap28_{family}_e{eew}_m{lmul}", kind, eew, lmul, 0))
    first = ["vqueue_gap28_widen_s_e32_m4", "vqueue_gap28_slide_e8_m2",
             "vqueue_gap28_store_e64_m4"]
    return sorted(result, key=lambda c: first.index(c[0]) if c[0] in first else 3)


def render(case):
    name, kind, eew, lmul, signed = case
    return "\n".join([
        "// SPDX-License-Identifier: SHL-0.51",
        "// Generated by verification/tests/generate_rvv_queue_gap28.py.",
        f'#define Q_NAME "{name}"', f"#define Q_KIND {kind}",
        f"#define Q_EEW {eew}", f"#define Q_WIDE {min(2 * eew, 64)}",
        f"#define Q_LMUL m{lmul}", f"#define Q_SIGNED {signed}",
        f"#define Q_LOAD_EEW {64 if eew == 8 else 8}",
        f'#define Q_WADD "{"vwadd" if signed else "vwaddu"}.vv v16, v8, v12, v0.t\\n"',
        '#include "vqueue_gap28_body.h"', ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEST)
    parser.add_argument("--selection", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    selection = {"tests": ["rvv:" + c[0] for c in cases()]}
    if args.selection:
        if args.check:
            if json.loads(args.selection.read_text()) != selection:
                raise SystemExit("selection differs")
        else:
            args.selection.write_text(json.dumps(selection, indent=2) + "\n")
    if not args.check:
        args.output_dir.mkdir(parents=True, exist_ok=True)
    for case in cases():
        path = args.output_dir / (case[0] + ".c")
        source = render(case)
        if args.check:
            if path.read_text() != source:
                raise SystemExit(f"generated source differs: {path}")
        else:
            path.write_text(source)


if __name__ == "__main__":
    main()
