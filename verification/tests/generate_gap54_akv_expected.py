#!/usr/bin/env python3
"""Deterministic independent bit patterns, generated before any DUT execution."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "apps/akv_gap54_skew_context/expected.h"


def payload(epoch, stream, dim):
    return 0x1100 + epoch*0x1000 + stream*0x2000 + dim*7


def pack(data):
    assert len(data)%8 == 0
    return [int.from_bytes(bytes(data[i:i+8]),"little") for i in range(0,len(data),8)]


def halves(values):
    return b"".join(v.to_bytes(2,"little") for v in values)


def arrays(name, dimensions, rows):
    shape = "".join(f"[{n}]" for n in dimensions)
    def nested(items, depth):
        if depth == len(dimensions)-1:
            return "{"+", ".join(f"UINT64_C(0x{v:016x})" for v in items)+"}"
        return "{\n"+",\n".join(nested(r,depth+1) for r in items)+"\n}"
    return f"static const uint64_t {name}{shape} __attribute__((aligned(64))) = "+nested(rows,0)+";\n"


def generate():
    sources,masks,rows = [],[],[]
    for epoch in range(2):
        es,em,er = [],[],[]
        for stream in range(3):
            start = 64 + ((2,6,14)[stream] if epoch == 0 else 0)
            data = bytearray((0xa7 + epoch*19 + stream*29 + b*11)&255 for b in range(256))
            row = halves([payload(epoch,stream,d) for d in range(64)])
            data[start:start+128] = row
            mask = bytearray(256)
            mask[start:start+128] = b"\x5a"*128
            es.append(pack(data))
            em.append(pack(mask))
            er.append(pack(row))
        sources.append(es)
        masks.append(em)
        rows.append(er)
    frames = []
    for phase in range(12):
        frames.append(pack(halves([0xc100+i for i in range(32)]+
            [0x9000+phase*0x100+i*13 for i in range(256)]+[0xd200+i for i in range(32)])))
    return ("/* Generated by generate_gap54_akv_expected.py; integer bit copies only. */\n"
        "#ifndef GAP54_EXPECTED_H\n#define GAP54_EXPECTED_H\n#include <stdint.h>\n"+
        arrays("source_reference",[2,3,32],sources)+arrays("poison_mask",[2,3,32],masks)+
        arrays("row_reference",[2,3,16],rows)+arrays("frame_reference",[12,80],frames)+"#endif\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit",action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.emit:
        print(expected,end="")
    else:
        if HEADER.read_text() != expected:
            raise SystemExit("generated independent oracle header differs")
        print("GAP54_EXPECTED PASS: source1536 + mask1536 + rows768 + frames7680 bytes")
