#!/usr/bin/env python3
"""Integer-only RNE binary32 oracle for exact seed fallback latency cases."""
import argparse
from pathlib import Path


def decode(bits):
    exponent=(bits>>23)&255
    fraction=bits&0x7fffff
    assert exponent!=255
    magnitude=fraction if exponent==0 else ((1<<23)|fraction)<<(exponent-1)
    return -magnitude if bits>>31 else magnitude


def round_rne(value):
    assert value>=0
    if value<(1<<23):
        return value,0
    shift=max(0,value.bit_length()-24)
    quotient=value>>shift
    remainder=value-(quotient<<shift)
    if shift and (remainder>(1<<(shift-1)) or
                  (remainder==(1<<(shift-1)) and quotient&1)):
        quotient+=1
    if quotient==(1<<24):
        quotient>>=1
        shift+=1
    exponent=shift+1
    assert exponent<255
    return (exponent<<23)|(quotient&0x7fffff),int(remainder!=0)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args()
    sums=[0,0,32,32<<149]
    seeds=[0x40400000,0x40400000,0x3f800000,1]
    rows=[]
    for source_sum,initial_seed in zip(sums,seeds):
        chains=[]
        for chain in (0,1):
            seed=initial_seed
            entries=[]
            for iteration in range(8):
                bits,flags=round_rne(source_sum+decode(seed))
                entries.append('{0x%08xU,0x%xU}'%(bits,flags))
                if chain:
                    seed=bits
            chains.append('{'+','.join(entries)+'}')
        rows.append('{'+','.join(chains)+'}')
    args.out.write_text('// Generated by integer-only gen_exact_seed_fallback_oracle.py\n'
                        'static const struct { uint32_t bits, flags; } expected[4][2][8] = {\n'
                        +',\n'.join(rows)+'\n};\n')


if __name__=='__main__':
    main()
