// Experimental full-product core. Not enabled in the production lane.
// Four SEW modes share radix-4 Booth rows and one partitioned Dadda tree.
module simd_mul_shared_product #(
  parameter bit FinishProduct = 1'b1
) (
  input logic [63:0] a_i, b_i,
  input logic [1:0] sew_i,
  input logic signed_a_i, signed_b_i,
  output logic [127:0] product_o,
  output wire [7:0][16:0] slice_sum_o
);
  wire [127:0] rows [34];
  wire [31:0] negative;
  wire [127:0] correction [4];
  wire [127:0] unsigned_top [4];
  wire [127:0] carry_mask;

  // Replacing the sign bit of each (N+2)-bit Booth row by its complement
  // avoids repeated sign extension. Compensate with a per-element constant.
  function automatic logic [127:0] booth_bias(int s);
    logic [127:0] result, local_bias;
    int n;
    result = '0;
    n = 8 << s;
    local_bias = '0;
    for (int q = 0; q < n; q += 2) local_bias -= 128'd1 << (n+1+q);
    for (int e = 0; e < 64/n; e++)
      for (int k = 0; k < 2*n; k++) result[e*2*n+k] = local_bias[k];
    return result;
  endfunction

  function automatic logic [127:0] support_mask(bit unsigned_row);
    logic [127:0] result;
    int n;
    result = '0;
    for (int s = 0; s < 4; s++) begin
      n = 8 << s;
      if (!unsigned_row) result |= booth_bias(s);
      for (int e = 0; e < 64/n; e++)
        for (int k = 0; k < n; k++) begin
          if (unsigned_row) result[e*2*n+n+k] = 1'b1;
          else if (k % 2 == 0) result[e*2*n+k] = 1'b1;
        end
    end
    return result;
  endfunction

  for (genvar r = 0; r < 32; r++) begin : gen_booth
    localparam int Q = 2*r;
    wire previous;
    if (Q == 0) assign previous = 1'b0;
    else assign previous = ((Q & ((8 << sew_i)-1)) == 0) ? 1'b0 : b_i[Q-1];
    wire one = b_i[Q] ^ previous;
    wire two = !(b_i[Q] ^ previous) && (b_i[Q+1] ^ b_i[Q]);
    assign negative[r] = b_i[Q+1];
    wire [65:0] a_mode [4], active_mode [4], sign_mode [4];
    for (genvar s = 0; s < 4; s++) begin : gen_mode
      localparam int N = 8 << s;
      localparam int Base = (Q/N)*N;
      wire sign_a = signed_a_i && a_i[Base+N-1];
      assign a_mode[s] = 66'({{2{sign_a}}, a_i[Base+:N]}) << Base;
      assign active_mode[s] = (66'h3ffffffffffffffff >> (64-N)) << Base;
      assign sign_mode[s] = 66'd1 << (Base+N+1);
    end
    wire [65:0] operand = a_mode[sew_i];
    wire [65:0] magnitude = ({66{one}} & operand) | ({66{two}} & (operand << 1));
    wire [65:0] word_value = (magnitude ^ {66{negative[r]}} ^ sign_mode[sew_i]) & active_mode[sew_i];
    assign rows[r] = 128'(word_value) << Q;
  end

  for (genvar s = 0; s < 4; s++) begin : gen_correction
    localparam int N = 8 << s;
    localparam logic [127:0] Bias = booth_bias(s);
    for (genvar e = 0; e < 64/N; e++) begin : gen_element
      // N/2 Booth groups interpret B as signed. The unsigned top-bit term
      // restores B's weight when requested, including signed A * unsigned B.
      assign unsigned_top[s][e*2*N+:N] = '0;
      assign unsigned_top[s][e*2*N+N+:N] = a_i[e*N+:N] &
          {N{!signed_b_i && b_i[e*N+N-1]}};
      for (genvar k = 0; k < 2*N; k++) begin : gen_bit
        // Row-negation +1 positions and bias bits are disjoint.
        if (k < N && k % 2 == 0)
          assign correction[s][e*2*N+k] = negative[(e*N+k)/2];
        else assign correction[s][e*2*N+k] = Bias[e*2*N+k];
      end
    end
  end
  assign rows[32] = correction[sew_i];
  assign rows[33] = unsigned_top[sew_i];
  for (genvar k = 0; k < 128; k++) begin : gen_carry_mask
    assign carry_mask[k] = ((k & ((16 << sew_i)-1)) != 0);
  end

  simd_mul_shared_dadda #(
    .CorrectionMask(support_mask(0)), .UnsignedMask(support_mask(1))
  ) i_tree (
    .rows_i(rows), .carry_mask_i(carry_mask), .slice_sum_o
  );
  if (FinishProduct) begin : gen_product
    simd_mul_shared_finish i_finish (
      .slice_sum_i(slice_sum_o), .sew_i, .product_o
    );
  end else begin : gen_partial
    assign product_o = '0;
  end
endmodule

module simd_mul_shared_dadda #(
  parameter logic [127:0] CorrectionMask = '1,
  parameter logic [127:0] UnsignedMask = '1
) (
  input wire [127:0] rows_i [34],
  input wire [127:0] carry_mask_i,
  output wire [7:0][16:0] slice_sum_o
);
  localparam int Stages = 8;
  typedef struct packed {
    logic [Stages:0][127:0][6:0] height;
    logic [Stages-1:0][127:0][5:0] fa;
    logic [Stages-1:0][127:0] ha;
  } plan_t;

  function automatic int first_row(int k);
    return k < 66 ? 0 : (k-64)/2;
  endfunction
  function automatic int row_bits(int k);
    return (k < 64 ? k/2 : 31) - first_row(k) + 1;
  endfunction

  // Elaborate a column-height schedule. Carries generated by column k in
  // one level enter column k+1 only in the NEXT level: no horizontal ripple.
  function automatic plan_t make_plan();
    plan_t p;
    int target, incoming, old_height, excess, nf, nh;
    p = '0;
    for (int k = 0; k < 128; k++)
      p.height[0][k] = 7'(row_bits(k) + int'(CorrectionMask[k]) + int'(UnsignedMask[k]));
    for (int s = 0; s < Stages; s++) begin
      case (s)
        0: target = 28; 1: target = 19; 2: target = 13;
        3: target = 9; 4: target = 6; 5: target = 4; 6: target = 3;
        default: target = 2;
      endcase
      incoming = 0;
      for (int k = 0; k < 128; k++) begin
        old_height = int'(p.height[s][k]);
        excess = old_height + incoming - target;
        if (excess < 0) excess = 0;
        nf = excess / 2;
        nh = excess % 2;
        p.fa[s][k] = 6'(nf);
        p.ha[s][k] = 1'(nh);
        p.height[s+1][k] = 7'(old_height - 2*nf - nh + incoming);
        incoming = nf + nh;
      end
    end
    return p;
  endfunction
  localparam plan_t Plan = make_plan();
  wire [64:0] heap [Stages+1][128];
  wire [64:0] carry [Stages][128];
  for (genvar k = 0; k < 128; k++) begin : gen_input
    localparam int First = first_row(k);
    localparam int Bits = row_bits(k);
    for (genvar b = 0; b < Bits; b++) begin : gen_bit
      assign heap[0][k][b] = rows_i[First+b][k];
    end
    if (CorrectionMask[k]) assign heap[0][k][Bits] = rows_i[32][k];
    if (UnsignedMask[k]) assign heap[0][k][Bits+int'(CorrectionMask[k])] = rows_i[33][k];
    if (Plan.height[0][k] < 65) assign heap[0][k][64:int'(Plan.height[0][k])] = '0;
  end
  for (genvar s = 0; s < Stages; s++) begin : gen_level
    for (genvar k = 0; k < 128; k++) begin : gen_column
      localparam int NF = int'(Plan.fa[s][k]);
      localparam int NH = int'(Plan.ha[s][k]);
      localparam int NC = NF+NH;
      localparam int Previous = k == 0 ? 0 : k-1;
      localparam int Incoming = k == 0 ? 0 : int'(Plan.fa[s][Previous])+int'(Plan.ha[s][Previous]);
      localparam int Used = 3*NF+2*NH;
      localparam int Remaining = int'(Plan.height[s][k])-Used;
      for (genvar f = 0; f < NF; f++) begin : gen_fa
        wire a = heap[s][k][3*f];
        wire b = heap[s][k][3*f+1];
        wire c = heap[s][k][3*f+2];
        assign heap[s+1][k][Incoming+f] = a ^ b ^ c;
        assign carry[s][k][f] = (a & b) | (a & c) | (b & c);
      end
      if (NH != 0) begin : gen_ha
        assign heap[s+1][k][Incoming+NF] = heap[s][k][3*NF] ^ heap[s][k][3*NF+1];
        assign carry[s][k][NF] = heap[s][k][3*NF] & heap[s][k][3*NF+1];
      end
      assign carry[s][k][64:NC] = '0;
      for (genvar b = 0; b < Incoming; b++) begin : gen_carry
        assign heap[s+1][k][b] = carry[s][Previous][b] & carry_mask_i[k];
      end
      for (genvar b = 0; b < Remaining; b++) begin : gen_bypass
        assign heap[s+1][k][Incoming+NC+b] = heap[s][k][Used+b];
      end
      assign heap[s+1][k][64:Incoming+NC+Remaining] = '0;
`ifndef SYNTHESIS
      initial begin
        assert (Remaining >= 0 && Incoming+NC+Remaining == int'(Plan.height[s+1][k]))
          else $fatal(1, "Invalid Dadda schedule stage=%0d column=%0d", s, k);
      end
`endif
    end
  end
  wire [127:0] final_rows [2];
  for (genvar k = 0; k < 128; k++) begin : gen_output
    assign final_rows[0][k] = heap[Stages][k][0];
    assign final_rows[1][k] = heap[Stages][k][1];
`ifndef SYNTHESIS
    initial assert (Plan.height[Stages][k] <= 2)
      else $fatal(1, "Unreduced Dadda column=%0d", k);
`endif
  end
  for (genvar k = 0; k < 8; k++) begin : gen_slice
    assign slice_sum_o[k] = {1'b0, final_rows[0][k*16+:16]} +
                            {1'b0, final_rows[1][k*16+:16]};
  end
endmodule

module simd_mul_shared_finish (
  input wire [7:0][16:0] slice_sum_i,
  input wire [1:0] sew_i,
  output wire [127:0] product_o
);
  // Product boundaries are twice the operand width. Only the registered
  // wide path needs the prefix; EW8 products are already complete per slice.
  wire [7:0] p [4], g [4];
  for (genvar k = 0; k < 8; k++) begin : gen_slice
    wire boundary = (k & ((1 << sew_i)-1)) == 0;
    assign p[0][k] = (&slice_sum_i[k][15:0]) && !boundary;
    assign g[0][k] = slice_sum_i[k][16];
    wire cin;
    if (k == 0) assign cin = 1'b0;
    else assign cin = boundary ? 1'b0 : g[3][k-1];
    assign product_o[k*16+:16] = slice_sum_i[k][15:0] + cin;
  end
  for (genvar l = 0; l < 3; l++) begin : gen_level
    for (genvar k = 0; k < 8; k++) begin : gen_prefix
      if (k >= (1 << l)) begin
        assign p[l+1][k] = p[l][k] & p[l][k-(1 << l)];
        assign g[l+1][k] = g[l][k] | (p[l][k] & g[l][k-(1 << l)]);
      end else begin
        assign p[l+1][k] = p[l][k];
        assign g[l+1][k] = g[l][k];
      end
    end
  end
endmodule
