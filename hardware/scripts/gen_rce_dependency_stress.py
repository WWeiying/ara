#!/usr/bin/env python3
"""Generate independent modular-integer expectations for overlapping RVV streams.

Four reductions, an ordinary add, a source-register overwrite and stores form
one uninterrupted vector sequence. Expected values are computed before RTL runs.
"""
import argparse
import json
from pathlib import Path
import random

OPS = ['vredsum.vs','vredand.vs','vredor.vs','vredxor.vs',
       'vredminu.vs','vredmin.vs','vredmaxu.vs','vredmax.vs',
       'vwredsumu.vs','vwredsum.vs']

def merge(op, width, values):
    mask = (1 << width)-1
    vals = [v & mask for v in values]
    if op in (0,8,9): return sum(vals) & mask
    if op in (1,2,3):
        acc = vals[0]
        for v in vals[1:]:
            acc = (acc & v) if op == 1 else (acc | v) if op == 2 else acc ^ v
        return acc
    if op in (5,7): vals = [v-(1<<width) if v>>(width-1) else v for v in vals]
    return (min(vals) if op in (4,5) else max(vals)) & mask

def scalar(x, width):
    return (x | (~((1 << width)-1)) if x>>(width-1) else x) & ((1<<64)-1)

def generate(destination, seed):
    destination.mkdir(exist_ok=False)
    rng=random.Random(seed)
    configurations=[(op,sew) for op in range(10) for sew in (8,16,32,64)
                    if not(op>=8 and sew==64)]
    declarations=[];blocks=[];records=[]
    for index,(op,sew) in enumerate(configurations*2):
        bits=sew*2 if op>=8 else sew
        vl=min([0,1,3,4,5,7,8,9,13,17,31][index%11],1024//sew)
        mask=(1<<sew)-1
        def val():
            return rng.choice([0,mask,1,1<<(sew-1),(1<<(sew-1))-1,rng.getrandbits(sew)])
        a=[val() for _ in range(vl)];b=[val() for _ in range(vl)]
        active=[False if index%5==0 else (j%2==0 if index%2==0 else bool(rng.getrandbits(1))) for j in range(vl)]
        start=rng.getrandbits(bits);add=[(x+y)&mask for x,y in zip(a,b)]
        def reduce(seed_value, values):
            if op==9: values=[v-(1<<sew) if v>>(sew-1) else v for v in values]
            return merge(op,bits,[seed_value]+values)
        r0=reduce(start,a) if vl else 0x5a
        r1=reduce(r0,[v for v,en in zip(b,active) if en]) if vl else 0x5a
        r2=reduce(r1,add) if vl else 0x5a
        r3=reduce(r2,b) if vl else 0x5a
        rawmask=sum(int(v)<<j for j,v in enumerate(active)).to_bytes(16,'little')
        def array(name,ctype,vals):
            vals=list(vals) or [0]
            declarations.append(f'static const {ctype} {name}_{index}[] __attribute__((aligned(128))) = {{'+','.join(hex(v) for v in vals)+'};')
        array('a',f'uint{sew}_t',a);array('b',f'uint{sew}_t',b);array('mask','uint8_t',rawmask);array('want',f'uint{sew}_t',add)
        asm=[f'vsetvli zero,zero,e{bits},m1,tu,mu','li t0,90','vmv.v.x v8,t0','vmv.v.x v10,t0','vmv.v.x v14,t0',
             f'vsetivli zero,1,e{bits},m1,tu,mu','vmv.s.x v2,%[seed]',
             f'vsetvli zero,%[vl],e{sew},m1,tu,mu',f'vle{sew}.v v4,(%[a])',f'vle{sew}.v v6,(%[b])','vlm.v v0,(%[mask])',
             f'{OPS[op]} v8,v4,v2','vadd.vv v12,v4,v6','vmv.v.i v4,7',
             f'{OPS[op]} v10,v6,v8,v0.t',f'{OPS[op]} v14,v12,v10',f'{OPS[op]} v8,v6,v14',
             f'vse{sew}.v v12,(%[out])',f'vsetivli zero,2,e{bits},m1,tu,mu',f'vse{bits}.v v10,(%[tail])',
             'vmv.x.s %[r1],v10','vmv.x.s %[r2],v14','vmv.x.s %[r3],v8']
        # rd=x0,rs1=x0 retains VL rather than selecting VLMAX. Use a nonzero
        # destination when initializing every destination element.
        asm[0]=f'vsetvli t0,zero,e{bits},m1,tu,mu'
        lines='\n'.join('      "'+s+'\\n"' for s in asm)
        blocks.append(f'''  {{
    uint64_t r1,r2,r3;
    for(unsigned j=0;j<sizeof(output);j++) output[j]=0xa5;
    asm volatile(
{lines}
      : [r1] "=&r"(r1),[r2] "=&r"(r2),[r3] "=&r"(r3)
      : [a] "r"(a_{index}),[b] "r"(b_{index}),[mask] "r"(mask_{index}),
        [seed] "r"(UINT64_C({start})),[vl] "r"((uint64_t){vl}),[out] "r"(output),[tail] "r"(tail)
      : "t0","memory");
    if(r1!=UINT64_C({scalar(r1,bits)}) || r2!=UINT64_C({scalar(r2,bits)}) || r3!=UINT64_C({scalar(r3,bits)}) || ((uint{bits}_t*)tail)[1]!=90) {{
      printf("FAIL dependency case={index} op={OPS[op]} sew={sew} vl={vl} r1=%lx r2=%lx r3=%lx tail=%lx\\n",r1,r2,r3,(uint64_t)((uint{bits}_t*)tail)[1]);return 1;
    }}
    for(unsigned j=0;j<{vl};j++) if(((uint{sew}_t*)output)[j]!=want_{index}[j]) {{printf("FAIL ordinary result case={index} element=%u\\n",j);return 1;}}
    if(output[{vl*(sew//8)}]!=0xa5) {{printf("FAIL store tail case={index}\\n");return 1;}}
  }}''')
        records.append({'case':index,'op':OPS[op],'sew':sew,'result_bits':bits,'vl':vl,'seed':start,'source_a':a,'source_b':b,'mask':active,'reduction_results':[r0,r1,r2,r3],'ordinary_result':add})
    header='// SPDX-License-Identifier: Apache-2.0\n// Generated by hardware/scripts/gen_rce_dependency_stress.py; do not edit expectations.\n#include <stdint.h>\n#include "printf.h"\n#include "runtime.h"\nstatic uint8_t output[256] __attribute__((aligned(128)));\nstatic uint8_t tail[16] __attribute__((aligned(128)));\n'
    text=header+'\n'.join(declarations)+'\nint main(void) {\n'+'\n'.join(blocks)+f'\n  printf("RCE dependency stress PASS: {len(records)} random streams, four reductions per stream, vector/tail checks\\n");return 0;\n}}\n'
    (destination/'main.c').write_text(text);(destination/'data.S').write_text('// No external data.\n');(destination/'cases.json').write_text(json.dumps({'seed':seed,'cases':records},indent=2)+'\n')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--destination',type=Path,required=True);p.add_argument('--seed',type=lambda s:int(s,0),default=0x524345DE)
    a=p.parse_args();generate(a.destination,a.seed)
