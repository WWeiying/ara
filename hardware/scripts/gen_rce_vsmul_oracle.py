#!/usr/bin/env python3
"""Generate independent integer expectations for VSMUL near RCE completion.

Python floor division models the arithmetic shift; rounding uses the exact
remainder, without replaying the RTL's bit slices. No host floating point.
"""
from pathlib import Path
import random


def rounded(a, b, width, mode):
    limit = 1 << (width - 1)
    if a == b == -limit:
        return limit - 1, 1
    q, rem = divmod(a * b, limit)
    if mode == 0:  # RNU: nearest, ties up
        inc = rem >= limit // 2
    elif mode == 1:  # RNE: nearest, ties to even
        inc = rem > limit // 2 or (rem == limit // 2 and q & 1)
    elif mode == 2:  # RDN: floor
        inc = False
    else:  # ROD: retain an odd low bit whenever inexact
        inc = bool(rem) and not (q & 1)
    return q + int(inc), 0


def generate():
    rng = random.Random(0x524345534154)
    cases = []
    for width in (8, 16, 32, 64):
        limit = 1 << (width - 1)
        edges = [-limit, -limit + 1, -limit // 2, -1, 0, 1, limit // 2, limit - 1]
        pairs = [(-limit, -limit), (-limit + 1, -limit // 2 + 1),
                 (1, limit // 2), (-1, limit // 2)]
        pairs += [(rng.choice(edges), rng.choice(edges)) for _ in range(128 // (width // 8))]
        count = 128 // (width // 8)
        for mode in range(4):
            for masked in range(3):
                aa, bb, expected = bytearray(), bytearray(), bytearray()
                mask = bytearray(16)
                sat = 0
                for i in range(count):
                    # Rotate the saturated element into both masked and active positions.
                    a, b = pairs[(i + mode) % len(pairs)]
                    active = masked == 0 or (masked == 1 and i % 3 != 0)
                    mask[i // 8] |= int(active) << (i % 8)
                    value, overflow = rounded(a, b, width, mode)
                    sat |= overflow if active else 0
                    encode = lambda v: (v & (2 * limit - 1)).to_bytes(width // 8, 'little')
                    aa.extend(encode(a)); bb.extend(encode(b))
                    expected.extend(encode(value) if active else bytes([0x5a]) * (width // 8))
                cases.append((width, mode, sat, aa, bb, mask, expected))
    def array(data):
        return '{' + ','.join(hex(x) for x in data) + '}'
    text = '// Generated by hardware/scripts/gen_rce_vsmul_oracle.py.\n'
    text += 'static const struct test_case cases[] __attribute__((aligned(128))) = {\n'
    for w, mode, sat, a, b, mask, result in cases:
        text += '  {' + f'{w},{mode},{sat},' + ','.join(array(x) for x in (a, b, mask, result)) + '},\n'
    return text + '};\n'


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[2]
    (root / 'apps/reduction_rce_vsmul_oracle/cases.h').write_text(generate())
