#!/usr/bin/env bash
# ============================================================================
# Unified HDV kernel sweep.
#
#   ./kernel_sweep.sh [--skip-long] [all|onepoint|point|1d|kernel|blas|blas_dim|blas_pf|blas_groups|vsgemm|fixed|long] [args]
#
# Options:
#   --skip-long     skip sweep points historically taking more than 10 minutes
#   --append        preserve existing kernel_sweep_out files before running
#
# Ablation:
#   HDV_ABLATION=full|base|vdu|ovlp|pf|pf_only|haz|pf_haz
#
# Everything is implemented here.  The old split sweep scripts are no longer
# called by this top-level flow.  All generated CSVs and logs go under:
#
#   hardware/kernel_sweep_out/
#
# Output files:
#   summary.txt          terminal transcript of this sweep run
#   kernel_all.csv       log-derived CSV generated by kernel_sweep_sum.sh
#   <kernel>.csv         per-kernel/per-variant CSVs
#   *.log                build/simulation logs
#
# fdotp and vspf are excluded from active testing.
# ============================================================================
set -uo pipefail
cd "$(dirname "$0")"

APPS=../apps
WD=400000
HDV_ABLATION="${HDV_ABLATION:-full}"
case "$HDV_ABLATION" in
  full|base|vdu|ovlp|pf|pf_only|haz|pf_haz) ;;
  *)
    echo "ERROR: invalid HDV_ABLATION=$HDV_ABLATION (use full|base|vdu|ovlp|pf|pf_only|haz|pf_haz)" >&2
    exit 2
    ;;
esac
export hdv_ablation="$HDV_ABLATION"

if [ -n "${KERNEL_SWEEP_OUT:-}" ]; then
  OUT="$KERNEL_SWEEP_OUT"
elif [ "$HDV_ABLATION" = "full" ]; then
  OUT=kernel_sweep_out
else
  OUT="kernel_sweep_out_${HDV_ABLATION}"
fi

usage() {
  echo "usage: $0 [--skip-long] [--append] {all|onepoint|point|1d|kernel|blas|blas_dim|blas_pf|blas_groups|vsgemm|fixed|long} [args]"
  echo "       HDV_ABLATION=base|vdu|ovlp|pf|full $0 --skip-long all"
  echo "       HDV_ABLATION=pf_only|haz|pf_haz $0 point vsaxpy_hdv 1024"
  echo "       KERNEL_SWEEP_OUT=my_out HDV_ABLATION=base $0 point vsaxpy_hdv 4096"
  echo "       KERNEL_SWEEP_SKIP_LONG=1 $0 all"
  echo "       $0 point vvaddint32_hdv 2048"
  echo "       $0 point lavamd_fix"
  echo "       $0 point vsgemm_m4_1r 128"
  echo "       $0 point vssyrk_hdv 128"
  echo "       $0 point vstrsm_hdv_m8 64"
  echo "       $0 point vsgemv_hdv_m4 128 8"
  echo "       $0 point vssymv_hdv_m4 128 8"
  echo "       $0 blas_groups \"128\" \"2 4 8\" \"4\""
  echo "       $0 long"
}

SKIP_LONG="${KERNEL_SWEEP_SKIP_LONG:-0}"
APPEND_OUT=0
POSITIONAL=()
while [ "$#" -gt 0 ]; do
  case "$1" in
    --skip-long|--fast)
      SKIP_LONG=1
      shift
      ;;
    --no-skip-long)
      SKIP_LONG=0
      shift
      ;;
    --append|--keep-out)
      APPEND_OUT=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      POSITIONAL+=("$1")
      shift
      ;;
  esac
done
set -- "${POSITIONAL[@]}"

MODE="${1:-all}"
ARG1="${2:-}"
ARG2="${3:-}"
ARG3="${4:-}"
ARG4="${5:-}"
if [ "$MODE" = "long" ] || [ "$MODE" = "point" ]; then
  APPEND_OUT=1
fi

mkdir -p "$OUT"
if [ "${KERNEL_SWEEP_LOCK_HELD:-0}" != "1" ]; then
  LOCK_NAME="${PWD//\//_}_${OUT//\//_}"
  exec 9>"/tmp/ara_hdv_kernel_sweep_${LOCK_NAME}.lock"
  if ! flock -n 9; then
    echo "[lock] another kernel sweep/sum is using $OUT; waiting..."
    flock 9
  fi
  export KERNEL_SWEEP_LOCK_HELD=1
fi
SUMMARY="$OUT/summary.txt"
if [ "$APPEND_OUT" = "1" ]; then
  touch "$SUMMARY"
else
  : > "$SUMMARY"
fi

# Keep summary.txt identical to the sweep's terminal transcript from this point
# onward.  Build and simulation details remain in their dedicated *.log files
# because those commands are explicitly redirected below.
exec > >(tee -a "$SUMMARY") 2>&1

if [ "$SKIP_LONG" = "1" ]; then
  echo "[skip-long] enabled: known >10min sweep points will be skipped"
fi
if [ "$HDV_ABLATION" != "full" ]; then
  echo "[ablation] mode=$HDV_ABLATION out=$OUT"
fi
if [ "$MODE" = "long" ]; then
  echo "[long] enabled: only known >10min sweep points will be run; existing output is preserved"
fi

log=""
kv() { grep -hE "$1" "$log" 2>/dev/null | grep -oE "$2[[:space:]]*=[[:space:]]*[0-9]+" | head -1 | grep -oE '[0-9]+$'; }
d()  { grep -hE "$1" "$log" 2>/dev/null | grep -oE "$2=[0-9]+" | head -1 | grep -oE '[0-9]+'; }

addr_of() {
  local hex
  hex=$(grep -E "[0-9a-f]+ [A-Za-z] $2\$" "$APPS/$1/$1.dump" 2>/dev/null | head -1 | awk '{print $1}')
  [ -z "$hex" ] && { echo ""; return 1; }
  printf '%d' "0x$hex"
}

one_d_ptr_plusargs() {
  local k=$1 s1 s2

  case "$k" in
    vstencil3_hdv)
      s1=$(addr_of "$k" src1)
      s2=$(addr_of "$k" src2)
      [ -n "$s1" ] && [ -n "$s2" ] && printf '+HDV_A1=%d +HDV_A2=%d ' "$((s1 + 4))" "$s2"
      ;;
    vfir5_hdv)
      s1=$(addr_of "$k" src1)
      s2=$(addr_of "$k" src2)
      [ -n "$s1" ] && [ -n "$s2" ] && printf '+HDV_A1=%d +HDV_A2=%d ' "$s1" "$s2"
      ;;
  esac
}

note() {
  echo "$*"
}

skip_long_note() {
  note "[skip-long] $*"
}

