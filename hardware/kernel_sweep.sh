run_blas_pf_point() {
  local k=$1 lm=$2 M=${3:-32} groups=${4:-1}
  local s1 s2 yoff ptrs tag log_suffix rows macc

  note "########## Single BLAS LMUL point: ${k}_m${lm} M=$M ##########"
  rm -f "$APPS/$k/main.c.o"
  ( cd "$APPS" && timeout 600 make bin/$k blas_lmul=$lm ) > "$OUT/build_blaspf_${k}_${lm}.log" 2>&1
  s1=$(addr_of "$k" src1); s2=$(addr_of "$k" src2)
  if [ -z "$s1" ]; then
    echo "  $k m$lm: BUILD/ADDR FAIL"
    return 1
  fi
  yoff=$((lm*128))
  case "$k" in
    vssymv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$M" ;;
    vsgemv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$((s2+yoff)) +HDV_A3=$M" ;;
    vstrsm_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$M" ;;
    *) return 1 ;;
  esac
  if { [ "$k" = "vssymv_hdv" ] || [ "$k" = "vsgemv_hdv" ]; } && [ "$groups" != "1" ]; then
    ptrs="$ptrs +HDV_A4=$groups"
  fi

  tag="${k}_m${lm}"
  log_suffix="${k}_${lm}_${M}"
  rows="$M"
  macc=$((M*lm*32))
  if { [ "$k" = "vssymv_hdv" ] || [ "$k" = "vsgemv_hdv" ]; } && [ "$groups" != "1" ]; then
    tag="${tag}_${groups}g"
    log_suffix="${log_suffix}_${groups}g"
    rows="$groups"
    macc=$((M*groups))
  fi
  echo "============== $k  m$lm  single LMUL point =============="
  printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
         "tag" "m$lm" "rows" "result" "cycles" "cyc/macc" "EPs" "vq_max" "pf_ar->hit" "seq_blk"
  log="$OUT/log_blaspf_${log_suffix}.log"
  if [ "$k" = "vstrsm_hdv" ] &&
     { { [ "$lm" = "2" ] && [ "$M" -ge 64 ]; } ||
       { [ "$lm" = "4" ] && [ "$M" -ge 64 ]; } ||
       { [ "$lm" = "8" ] && [ "$M" -ge 32 ]; }; }; then
    timeout 3600 make sim app=$k \
      hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000 +HDV_TASK_WATCHDOG=800000" > "$log" 2>&1
  else
    timeout 600 make sim app=$k \
      hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000" > "$log" 2>&1
  fi
  parse_blas_perf "$tag" "$lm" "$rows" "$M" "$macc"
}

run_vsgemm_point() {
  local lmul=$1 rows=$2 n=${3:-32}
  local tag="vsgemm_m${lmul}_${rows}r" s1 s2 macc

  if [ "$lmul" = "1" ] && [ "$rows" != "4" ] && [ "$n" != "32" ]; then
    echo "  $tag: invalid N=$n; m1 ${rows}r vsgemm is fixed 32x32x32."
    return 1
  fi
  if [ "$lmul" = "1" ] && [ "$rows" = "4" ] &&
     [ "$n" != "32" ] && [ "$n" != "64" ] && [ "$n" != "128" ]; then
    echo "  $tag: invalid N=$n; m1 4r vsgemm supports N=32/64/128."
    return 1
  fi

  note "########## Single vsgemm point: $tag N=$n ##########"
  rm -f "$APPS/vsgemm_hdv/main.c.o"
  ( cd "$APPS" && timeout 600 make bin/vsgemm_hdv gemm_lmul=$lmul gemm_rows=$rows gemm_n=$n ) \
    > "$OUT/build_${tag}.log" 2>&1
  s1=$(addr_of vsgemm_hdv src1); s2=$(addr_of vsgemm_hdv src2)
  if [ -z "$s1" ] || [ -z "$s2" ]; then
    echo "  $tag: BUILD/ADDR FAIL"
    return 1
  fi

  echo "==================== vsgemm single point ===================="
  printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
         "tag" "N" "rows" "result" "cycles" "cyc/macc" "EPs" "vq_max" "pf_ar->hit" "seq_blk"
  log="$OUT/log_blas_${tag}_${n}.log"
  if { [ "$lmul" = "4" ] && [ "$rows" != "4" ] && [ "$n" -ge 64 ]; } ||
     { [ "$lmul" = "4" ] && [ "$rows" = "4" ] && [ "$n" -ge 128 ]; } ||
     { [ "$lmul" = "1" ] && [ "$rows" = "4" ] && [ "$n" -ge 64 ]; }; then
    timeout 3600 make sim app=vsgemm_hdv \
      hdv_plusargs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$n +HDV_EXPECTED_EP=8000000 +HDV_TASK_WATCHDOG=1000000" \
      > "$log" 2>&1
  else
    timeout 600 make sim app=vsgemm_hdv \
      hdv_plusargs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$n +HDV_EXPECTED_EP=8000000" \
      > "$log" 2>&1
  fi
  if [ "$lmul" = "1" ] && [ "$rows" != "4" ]; then
    macc=32768
  else
    macc=$((n*n*n))
  fi
  parse_blas_perf "$tag" "$n" "$rows" "$n" "$macc"
}

run_point() {
  local name=$1 a=${2:-} b=${3:-} c=${4:-}
  if [ -z "$name" ]; then
    echo "usage: $0 point <kernel-or-tag> [avl|size|M|N] [extra]"
    return 1
  fi

  case "$name" in
    vsaxpy_hdv|vvaddint32_hdv|vscopy_hdv|vsswap_hdv|vsdot_hdv|vsscal_hdv|vmc_hdv|dropout_hdv|vsdwt_hdv|vstencil3_hdv|vfir5_hdv)
      run_1d_point "$name" "${a:-1024}"
      return
      ;;
    vsger_hdv|vssymv_hdv|vssyrk_hdv|vstrsm_hdv|vsgemv_hdv)
      run_blas_dim_point "$name" "${a:-32}"
      return
      ;;
    vssymv_hdv_m[248]|vsgemv_hdv_m[248]|vstrsm_hdv_m[248])
      local base=${name%_m[248]} lm=${name##*_m}
      run_blas_pf_point "$base" "$lm" "${a:-32}" "${b:-1}"
      return
      ;;
    vsgemm_m*_?r)
      if [[ "$name" =~ ^vsgemm_m([0-9]+)_([0-9]+)r$ ]]; then
        run_vsgemm_point "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}" "${a:-32}"
        return
      fi
      ;;
    vsgemm_hdv)
      run_vsgemm_point "${a:-4}" "${b:-1}" "${c:-32}"
      return
      ;;
    *_fix)
      run_fixed_named "$name"
      return
      ;;
  esac

  echo "unknown point '$name'"
  echo "examples:"
  echo "  $0 point vvaddint32_hdv 2048"
  echo "  $0 point lavamd_fix"
  echo "  $0 point vsgemm_m4_1r 128"
  echo "  $0 point vssyrk_hdv 128"
  echo "  $0 point vstrsm_hdv_m8 64"
  echo "  $0 point vsgemv_hdv_m4 128 8"
  echo "  $0 point vssymv_hdv_m4 128 8"
  return 1
}

