BLAS_ROWHDR="$KERNEL_ROWHDR"
declare -A BLAS_TAG_INIT=()

ensure_blas_tag_csv() {
  local tag=$1
  if [ -z "${BLAS_TAG_INIT[$tag]+x}" ]; then
    if [ "$APPEND_OUT" = "1" ] && [ -s "$OUT/${tag}.csv" ]; then
      :
    else
      echo "$BLAS_ROWHDR" > "$OUT/${tag}.csv"
    fi
    BLAS_TAG_INIT[$tag]=1
  fi
}

drop_existing_blas_row() {
  local tag=$1 size=$2 rows=$3 n=$4 csv="$OUT/${tag}.csv"
  if [ "$APPEND_OUT" != "1" ] || [ ! -s "$csv" ]; then
    return
  fi
  local tmp
  tmp=$(mktemp)
  awk -F, -v tag="$tag" -v size="$size" -v rows="$rows" -v n="$n" \
    'NR == 1 || !($2 == tag && $5 == size && $6 == rows && $7 == n)' \
    "$csv" > "$tmp"
  mv "$tmp" "$csv"
}

parse_blas_perf() {
  local tag=$1 size=$2 rows=$3 n=$4 macc=$5
  ensure_blas_tag_csv "$tag"
  drop_existing_blas_row "$tag" "$size" "$rows" "$n"
  write_kernel_csv_row "blas" "$tag" "$tag" "" "$size" "$rows" "$n" 0 "$macc" "$OUT/${tag}.csv"

  local r tc eps cpm vqmax pfa pfh sblk
  r=$(grep -E 'mock host' "$log" | head -1 | grep -oE 'PASSED|FAILED'); [ -z "$r" ] && r="ERR"
  tc=$(kv 'mock host' 'total_task_cycles')
  eps=$(d 'HDV-CSR.*DONE' 'accepted'); [ -z "$eps" ] && eps=$(grep -E 'mock host' "$log" | grep -oE 'got [0-9]+' | grep -oE '[0-9]+')
  cpm="-"; [ -n "$tc" ] && [ "$macc" -gt 0 ] 2>/dev/null && cpm=$(echo "scale=4; $tc/$macc" | bc)
  vqmax=$(kv 'HDV-PERF' 'vq_max_occupancy')
  pfa=$(kv 'PERF-ADDRGEN\]' 'pf_ar')
  pfh=$(kv 'PERF-ADDRGEN\]' 'pf_hit')
  sblk=$(kv 'PERF-SEQ' 'blocked')
  printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
         "$tag" "$size" "$rows" "$r" "${tc:--}" "$cpm" "${eps:--}" "${vqmax:--}" \
         "${pfa:--}->${pfh:--}" "${sblk:--}"
}

sweep_vsgemm() {
  local ns="${1:-16 32 64 128}"
  note "########## Group 2A: vsgemm ##########"
  echo "==================== vsgemm  {lmul}x{rows}x{N} ===================="
  printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
         "tag" "N" "rows" "result" "cycles" "cyc/macc" "EPs" "vq_max" "pf_ar->hit" "seq_blk"

  local lmul rows n nlist tag s1 s2 macc
  for lmul in 1 4; do
    for rows in 1 2 4; do
      nlist="$ns"
      [ "$lmul" = "1" ] && [ "$rows" != "4" ] && nlist="32"
      [ "$lmul" = "1" ] && [ "$rows" = "4" ] && nlist="32 64 128"
      for n in $nlist; do
        tag="vsgemm_m${lmul}_${rows}r"
        rm -f "$APPS/vsgemm_hdv/main.c.o"
        ( cd "$APPS" && timeout 600 make bin/vsgemm_hdv gemm_lmul=$lmul gemm_rows=$rows gemm_n=$n ) \
          > "$OUT/build_vsgemm_m${lmul}_${rows}r_${n}.log" 2>&1
        s1=$(addr_of vsgemm_hdv src1); s2=$(addr_of vsgemm_hdv src2)
        if [ -z "$s1" ] || [ -z "$s2" ]; then
          echo "  vsgemm m${lmul} ${rows}r N=$n: BUILD/ADDR FAIL"
          continue
        fi
        log="$OUT/log_blas_${tag}_${n}.log"
        if [ "$SKIP_LONG" = "1" ] &&
           { { [ "$lmul" = "4" ] && [ "$n" -ge 128 ]; } ||
             { [ "$lmul" = "1" ] && [ "$rows" = "4" ] && [ "$n" -ge 128 ]; }; }; then
          skip_long_note "$tag N=$n"
          printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
                 "$tag" "$n" "$rows" "SKIP" "-" "-" "-" "-" "-->-" "over_10min"
          continue
        fi
        if { [ "$lmul" = "4" ] && [ "$rows" != "4" ] && [ "$n" -ge 64 ]; } ||
           { [ "$lmul" = "4" ] && [ "$rows" = "4" ] && [ "$n" -ge 128 ]; } ||
           { [ "$lmul" = "1" ] && [ "$rows" = "4" ] && [ "$n" -ge 64 ]; }; then
          timeout 3600 make sim app=vsgemm_hdv \
            hdv_plusargs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$n +HDV_EXPECTED_EP=8000000 +HDV_TASK_WATCHDOG=1000000" \
            > "$log" 2>&1
        else
          timeout 600 make sim app=vsgemm_hdv \
            hdv_plusargs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$n +HDV_EXPECTED_EP=8000000" \
            > "$log" 2>&1
        fi
        if [ "$lmul" = "1" ] && [ "$rows" != "4" ]; then
          macc=32768
        else
          macc=$((n*n*n))
        fi
        parse_blas_perf "$tag" "$n" "$rows" "$n" "$macc"
      done
    done
  done
}

sweep_blas_dim() {
  local ns="${1:-16 32 64 128}"
  note "########## Group 2B: BLAS dim sweep ##########"

  declare -A b_dimreg=( [vssymv_hdv]=A3 [vssyrk_hdv]=A2 [vstrsm_hdv]=A2
                        [vsger_hdv]=A1  [vsgemv_hdv]=A3 )
  local k n s1 s2 reg ptrs macc
  for k in vsger_hdv vssymv_hdv vssyrk_hdv vstrsm_hdv vsgemv_hdv; do
    rm -f "$APPS/$k/main.c.o"
    ( cd "$APPS" && timeout 600 make bin/$k blas_lmul=4 ) > "$OUT/build_blas_${k}.log" 2>&1
    s1=$(addr_of "$k" src1); s2=$(addr_of "$k" src2)
    if [ -z "$s1" ]; then
      echo "  $k: BUILD/ADDR FAIL"
      continue
    fi
    echo "==================== $k  (dim sweep) ===================="
    printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
           "tag" "size" "rows" "result" "cycles" "cyc/macc" "EPs" "vq_max" "pf_ar->hit" "seq_blk"
    reg=${b_dimreg[$k]}
    for n in $ns; do
      case "$k" in
        vsger_hdv)  ptrs="+HDV_A0=128 +HDV_A2=$s2 +HDV_A3=$((s2+512)) +HDV_A4=$s1 +HDV_A1=$n" ;;
        vssymv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$n" ;;
        vssyrk_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$n" ;;
        vstrsm_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$n" ;;
        vsgemv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$((s2+512)) +HDV_A3=$n" ;;
      esac
      log="$OUT/log_blas_${k}_${n}.log"
      if [ "$SKIP_LONG" = "1" ] &&
         { { [ "$k" = "vssyrk_hdv" ] && [ "$n" -ge 64 ]; } ||
           { [ "$k" = "vstrsm_hdv" ] && [ "$n" -ge 128 ]; }; }; then
        skip_long_note "$k N=$n"
        printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
               "$k" "$n" "-" "SKIP" "-" "-" "-" "-" "-->-" "over_10min"
        continue
      fi
      if { [ "$k" = "vssyrk_hdv" ] && [ "$n" -ge 32 ]; } ||
         { [ "$k" = "vstrsm_hdv" ] && [ "$n" -ge 64 ]; }; then
        timeout 3600 make sim app=$k \
          hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000 +HDV_TASK_WATCHDOG=800000" > "$log" 2>&1
      else
        timeout 600 make sim app=$k \
          hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000" > "$log" 2>&1
      fi
      if [ "$k" = "vsger_hdv" ]; then
        macc=$((128*n))
      else
        macc=$((n*n))
      fi
      parse_blas_perf "$k" "$n" "-" "$n" "$macc"
    done
  done
}

sweep_blas_pf() {
  local ms="${1:-32 64}"
  note "########## Group 2C: BLAS LMUL prefetch sweep ##########"

  local k lm M s1 s2 yoff ptrs
  for k in vssymv_hdv vsgemv_hdv vstrsm_hdv; do
    for lm in 2 4 8; do
      rm -f "$APPS/$k/main.c.o"
      ( cd "$APPS" && timeout 600 make bin/$k blas_lmul=$lm ) > "$OUT/build_blaspf_${k}_${lm}.log" 2>&1
      s1=$(addr_of "$k" src1); s2=$(addr_of "$k" src2)
      if [ -z "$s1" ]; then
        echo "  $k m$lm: BUILD/ADDR FAIL"
        continue
      fi
      yoff=$((lm*128))
      echo "============== $k  m$lm  (LMUL prefetch sweep) =============="
      printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
             "tag" "m$lm" "rows" "result" "cycles" "cyc/macc" "EPs" "vq_max" "pf_ar->hit" "seq_blk"
      for M in $ms; do
        case "$k" in
          vssymv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$M" ;;
          vsgemv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$((s2+yoff)) +HDV_A3=$M" ;;
          vstrsm_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$M" ;;
        esac
        log="$OUT/log_blaspf_${k}_${lm}_${M}.log"
        if [ "$SKIP_LONG" = "1" ] && [ "$k" = "vstrsm_hdv" ] &&
           [ "$lm" = "8" ] && [ "$M" -ge 64 ]; then
          skip_long_note "${k}_m${lm} M=$M"
          printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
                 "${k}_m${lm}" "$lm" "$M" "SKIP" "-" "-" "-" "-" "-->-" "over_10min"
          continue
        fi
        if [ "$k" = "vstrsm_hdv" ] &&
           { { [ "$lm" = "2" ] && [ "$M" -ge 64 ]; } ||
             { [ "$lm" = "4" ] && [ "$M" -ge 64 ]; } ||
             { [ "$lm" = "8" ] && [ "$M" -ge 32 ]; }; }; then
          timeout 3600 make sim app=$k \
            hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000 +HDV_TASK_WATCHDOG=800000" > "$log" 2>&1
        else
          timeout 600 make sim app=$k \
            hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000" > "$log" 2>&1
        fi
        parse_blas_perf "${k}_m${lm}" "$lm" "$M" "$M" "$((M*lm*32))"
      done
    done
  done
}

sweep_blas_groups() {
  local ns="${1:-128}" groups_list="${2:-2 4 8}" lms="${3:-4}"
  note "########## Group 2D: BLAS GEMV/SYMV multi-row sweep ##########"

  local k lm n groups s1 s2 yoff ptrs tag log macc vlmax
  for k in vssymv_hdv vsgemv_hdv; do
    for lm in $lms; do
      rm -f "$APPS/$k/main.c.o"
      ( cd "$APPS" && timeout 600 make bin/$k blas_lmul=$lm ) > "$OUT/build_blasgrp_${k}_${lm}.log" 2>&1
      s1=$(addr_of "$k" src1); s2=$(addr_of "$k" src2)
      if [ -z "$s1" ]; then
        echo "  $k m$lm: BUILD/ADDR FAIL"
        continue
      fi
      yoff=$((lm*128))
      vlmax=$((lm*32))
      echo "============== $k  m$lm  (multi-row sweep) =============="
      printf "%-18s %-5s %-5s %-7s %-8s %-9s %-7s %-7s %-9s %s\n" \
             "tag" "N" "rows" "result" "cycles" "cyc/macc" "EPs" "vq_max" "pf_ar->hit" "seq_blk"
      for n in $ns; do
        if [ "$n" -gt "$vlmax" ]; then
          note "[skip] ${k}_m${lm} N=$n rows=* skipped: N exceeds VLMAX=$vlmax"
          continue
        fi
        for groups in $groups_list; do
          case "$k" in
            vssymv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$s1 +HDV_A3=$n +HDV_A4=$groups" ;;
            vsgemv_hdv) ptrs="+HDV_A0=$s1 +HDV_A1=$s2 +HDV_A2=$((s2+yoff)) +HDV_A3=$n +HDV_A4=$groups" ;;
          esac
          tag="${k}_m${lm}_${groups}g"
          log="$OUT/log_blaspf_${k}_${lm}_${n}_${groups}g.log"
          timeout 600 make sim app=$k \
            hdv_plusargs="$ptrs +HDV_EXPECTED_EP=8000000" > "$log" 2>&1
          macc=$((n*groups))
          parse_blas_perf "$tag" "$lm" "$groups" "$n" "$macc"
        done
      done
    done
  done
}

sweep_blas_all() {
  local ns="${1:-16 32 64 128}"
  sweep_blas_dim "$ns"
  sweep_blas_pf "32 64"
  sweep_blas_groups "128" "2 4 8" "4"
  sweep_vsgemm "$ns"
}

